    '  }',
    '',
    '  function windowUrl(webContents) {',
    '    return attempt(function () {',
    '      var value = webContents.getURL();',
    "      return typeof value === 'string' ? value : '';",
    "    }, '');",
    '  }',
    '',
    '  function windowTitle(webContents) {',
    '    return attempt(function () {',
    '      var value = webContents.getTitle();',
    "      return typeof value === 'string' ? value : '';",
    "    }, '');",
    '  }',
    '',
    '  function isDestroyed(webContents) {',
