    '    return value;',
    '  }',
    '',
    '  function snapshotWindows() {',
    '    var output = [];',
    '    for (var index = 0; index < state.windows.length; index += 1) {',
    '      output.push(snapshotWindow(state.windows[index]));',
    '    }',
    '    return output;',
    '  }',
    '',
