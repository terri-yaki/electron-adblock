// Main-process inspector bootstrap for apps whose windows are missing from the CDP target list
// (for example TFTAcademy, where the Electron window uses a custom scheme). The source is
// evaluated once inside the app main process through the Node inspector, then driven by
// InspectorEngine through globalThis.__eadInspectorApi. All Electron access stays inside that
// evaluated source; this module never imports electron.

export const INSPECTOR_API_GLOBAL = '__eadInspectorApi';
export const INSPECTOR_BOOTSTRAP_VERSION = 3;
export const INSPECTOR_INJECTED_GLOBAL = '__electronAdblock';
export const INSPECTOR_INJECTED_BINDING = '__electronAdblockReport';

/** Window snapshot reported by the bootstrap. */
export interface InspectorWindowSnapshot {
  id: number;
  url: string;
  title: string;
  attached: boolean;
  error?: string;
}

/** Per-window result of applying cosmetic/layout payloads. */
export interface InspectorApplyWindowResult {
  windowId: number;
  url: string;
  hidden: number;
  ok: boolean;
  error?: string;
}

/** Raw result of the bootstrap drainReports() call. */
export interface InspectorDrainPayload {
  reports?: unknown;
  blockedLogs?: unknown;
  blockedCount?: unknown;
  lastBlockedAt?: unknown;
  windows?: unknown;
  electronVersion?: unknown;
  electron?: unknown;
  electronError?: unknown;
}

/** Raw result of the bootstrap configureSource()/setPatterns()/sync() calls. */
export interface InspectorSyncPayload {
  windows?: unknown;
  electronVersion?: unknown;
  electron?: unknown;
  electronError?: unknown;
  enabled?: unknown;
  patterns?: unknown;
}

const GLOB_MATCHER_PLACEHOLDER = '/*__EAD_GLOB_MATCHER__*/';

/**
 * Self-contained matcher source embedded into the evaluated bootstrap. Keep this plain ES5
 * style JavaScript: it runs inside a foreign main process, not in this bundle.
 */
export const INSPECTOR_GLOB_MATCHER_SOURCE = "function buildGlobMatcher(patterns) {\n  var backslash = String.fromCharCode(92);\n  var specials = \"^$.*+?()[]{}|\" + backslash;\n  function escapeGlobCharacter(character) {\n    return specials.indexOf(character) >= 0 ? backslash + character : character;\n  }\n  var regexes = [];\n  if (Array.isArray(patterns)) {\n    for (var index = 0; index < patterns.length; index += 1) {\n      var pattern = patterns[index];\n      if (typeof pattern !== \"string\" || pattern.length === 0) continue;\n      var source = \"^\";\n      for (var characterIndex = 0; characterIndex < pattern.length; characterIndex += 1) {\n        var character = pattern[characterIndex];\n        if (character === backslash && characterIndex + 1 < pattern.length) {\n          characterIndex += 1;\n          source += escapeGlobCharacter(pattern[characterIndex]);\n          continue;\n        }\n        if (character === \"*\") { source += \".*\"; continue; }\n        if (character === \"?\") { source += \".\"; continue; }\n        source += escapeGlobCharacter(character);\n      }\n      try { regexes.push(new RegExp(source + \"$\", \"i\")); } catch (error) {}\n    }\n  }\n  return function (url) {\n    if (typeof url !== \"string\" || url.length === 0) return false;\n    for (var regexIndex = 0; regexIndex < regexes.length; regexIndex += 1) {\n      if (regexes[regexIndex].test(url)) return true;\n    }\n    return false;\n  };\n}";

export type GlobMatcherFactory = (patterns: readonly string[]) => (url: string) => boolean;

let cachedGlobMatcherFactory: GlobMatcherFactory | null = null;

function createGlobMatcherFactory(): GlobMatcherFactory {
  if (!cachedGlobMatcherFactory) {
    cachedGlobMatcherFactory = new Function(
      'return (' + INSPECTOR_GLOB_MATCHER_SOURCE + ');',
    )() as GlobMatcherFactory;
  }
  return cachedGlobMatcherFactory;
}

/** Compiles normalized URL globs into a matcher (the bootstrap embeds the same source text). */
export function buildGlobMatcher(patterns: readonly string[]): (url: string) => boolean {
  return createGlobMatcherFactory()(patterns);
}

