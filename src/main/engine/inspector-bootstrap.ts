    '      }',
    '      record.attached = true;',
    '      record.owned = true;',
    '      record.attachBlockedUntil = 0;',
    '      record.initialized = false;',
    "      record.lastError = '';",
    '    }',
    '    if (!record.listener) {',
    '      record.listener = true;',
    '      attempt(function () {',
    "        record.webContents.debugger.on('message', function (event, method, params) {",
    '          try {',
    '            handleMessage(record, event, method, params);',
    '          } catch (error) {',
    '            // Ignore listener failures; the host keeps polling.',
    '          }',
    '        });',
    '        return true;',
    '      }, false);',
    '    }',
    '    if (!record.initialized) {',
    '      record.initialized = true;',
